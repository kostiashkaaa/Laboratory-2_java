package ru.spbstu.mousemaze.model;

/**
 * Результат одного шага агента в среде.
 *
 * <p>{@code done} и {@code terminal} — разные понятия. {@code done} означает
 * только "цикл эпизода должен остановиться" (в том числе из-за исчерпания
 * лимита шагов). {@code terminal} означает, что агент действительно достиг
 * конца MDP (цель или фатальная ловушка) — то есть у состояния объективно
 * нет будущей награды. Обрыв по лимиту шагов — это не терминальное состояние
 * среды, а лишь техническое ограничение на длину эпизода: агент мог бы
 * продолжать действовать и дальше, если бы лимит не истёк. Поэтому при
 * обновлении Q-значений (уравнение Беллмана) нужно бутстрапить будущую
 * ценность по {@code terminal}, а не по {@code done} — иначе каждый эпизод,
 * оборвавшийся по таймауту, ошибочно учит агента, что "после этого состояния
 * будущего нет", хотя на самом деле это неверно и приводит к систематическому
 * занижению Q-значений почти во всём лабиринте.
 *
 * @param state    новое состояние
 * @param reward   полученная награда
 * @param done     признак того, что цикл эпизода должен остановиться
 *                 (терминал ИЛИ исчерпан лимит шагов)
 * @param blocked  признак столкновения со стеной или границей
 * @param terminal признак настоящего завершения MDP (цель или ловушка,
 *                 завершающая эпизод) — без будущей ценности для бутстрапа
 */
public record StepResult(Position state, double reward, boolean done, boolean blocked, boolean terminal) { }
